nums = [1,2,3]
# append - add one element at the last
nums.append(4)
print (nums)

# insert - insert element at idx
nums.insert(2,10)
print (nums)

# sort - arranges in increasing order
nums.sort()
print(nums)

nums.sort(reverse = True)
print(nums)

# reverse - reverses order
nums.reverse()
print(nums)